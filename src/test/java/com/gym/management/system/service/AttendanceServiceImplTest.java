package com.gym.management.system.service;

import com.gym.management.system.dto.mapper.AttendanceDTOMapper;
import com.gym.management.system.dto.response.AttendanceResponseDTO;
import com.gym.management.system.entity.Attendance;
import com.gym.management.system.entity.Member;
import com.gym.management.system.exception.InvalidInputException;
import com.gym.management.system.exception.NotFoundException;
import com.gym.management.system.repository.AttendanceRepository;
import com.gym.management.system.repository.MemberRepository;
import com.gym.management.system.service.implementationclasses.AttendanceServiceImpl;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;

import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
public class AttendanceServiceImplTest {

    @Mock
    private AttendanceRepository attendanceRepository;

    @Mock
    private MemberRepository memberRepository;

    @Mock
    private AttendanceDTOMapper attendanceDTOMapper;

    @InjectMocks
    private AttendanceServiceImpl attendanceService;

    // ─── Shared test data ────────────────────────────────────────────────

    private Member member;
    private Attendance attendance;
    private AttendanceResponseDTO responseDTO;

    @BeforeEach
    void setUp() {

        // Fake member — id is auto-generated by DB, we just set it here to wire up relationships
        member = new Member();
        member.setMemberId(1L);

        // Fake attendance record — checked in but not yet checked out
        attendance = new Attendance();
        attendance.setMember(member);
        attendance.setDate(LocalDate.now());
        attendance.setCheckInTime(LocalTime.of(9, 0));
        attendance.setCheckOutTime(null); // not checked out yet

        // Fake response DTO returned by mapper
        responseDTO = new AttendanceResponseDTO();
    }

    // ════════════════════════════════════════════════════════════
    // checkIn() tests
    // ════════════════════════════════════════════════════════════

    @Test
    void checkIn_ShouldReturnResponse_WhenMemberHasNotCheckedInToday() {

        // Arrange — member exists, no check-in yet today
        when(memberRepository.findById(1L)).thenReturn(Optional.of(member));
        when(attendanceRepository.findByMemberMemberIdAndDate(1L, LocalDate.now()))
                .thenReturn(Optional.empty()); // no record for today
        when(attendanceRepository.save(any(Attendance.class))).thenReturn(attendance);
        when(attendanceDTOMapper.toResponse(attendance)).thenReturn(responseDTO);

        // Act
        AttendanceResponseDTO result = attendanceService.checkIn(1L);

        // Assert
        assertNotNull(result);
        verify(attendanceRepository).save(any(Attendance.class));
    }

    @Test
    void checkIn_ShouldThrowNotFoundException_WhenMemberDoesNotExist() {

        // Arrange — member not found in DB
        when(memberRepository.findById(99L)).thenReturn(Optional.empty());

        // Act & Assert
        assertThrows(NotFoundException.class,
                () -> attendanceService.checkIn(99L));
    }

    @Test
    void checkIn_ShouldThrowInvalidInputException_WhenMemberAlreadyCheckedInToday() {

        // Arrange — member exists and already has a check-in record for today
        when(memberRepository.findById(1L)).thenReturn(Optional.of(member));
        when(attendanceRepository.findByMemberMemberIdAndDate(1L, LocalDate.now()))
                .thenReturn(Optional.of(attendance)); // already checked in

        // Act & Assert
        assertThrows(InvalidInputException.class,
                () -> attendanceService.checkIn(1L));
    }

    // ════════════════════════════════════════════════════════════
    // checkOut() tests
    // ════════════════════════════════════════════════════════════

    @Test
    void checkOut_ShouldReturnResponse_WhenMemberHasCheckedInAndNotYetCheckedOut() {

        // Arrange — member exists, has checked in, checkout time is null
        when(memberRepository.existsById(1L)).thenReturn(true);
        when(attendanceRepository.findByMemberMemberIdAndDate(1L, LocalDate.now()))
                .thenReturn(Optional.of(attendance)); // attendance exists, checkOutTime is null
        when(attendanceRepository.save(any(Attendance.class))).thenReturn(attendance);
        when(attendanceDTOMapper.toResponse(attendance)).thenReturn(responseDTO);

        // Act
        AttendanceResponseDTO result = attendanceService.checkOut(1L);

        // Assert
        assertNotNull(result);
        verify(attendanceRepository).save(any(Attendance.class));
    }

    @Test
    void checkOut_ShouldThrowNotFoundException_WhenMemberDoesNotExist() {

        // Arrange — member not in DB
        when(memberRepository.existsById(99L)).thenReturn(false);

        // Act & Assert
        assertThrows(NotFoundException.class,
                () -> attendanceService.checkOut(99L));
    }

    @Test
    void checkOut_ShouldThrowNotFoundException_WhenMemberHasNotCheckedInToday() {

        // Arrange — member exists but no attendance record found for today
        when(memberRepository.existsById(1L)).thenReturn(true);
        when(attendanceRepository.findByMemberMemberIdAndDate(1L, LocalDate.now()))
                .thenReturn(Optional.empty()); // no check-in record

        // Act & Assert
        assertThrows(NotFoundException.class,
                () -> attendanceService.checkOut(1L));
    }

    @Test
    void checkOut_ShouldThrowInvalidInputException_WhenMemberAlreadyCheckedOut() {

        // Arrange — member already has a check-out time set
        attendance.setCheckOutTime(LocalTime.of(17, 0)); // already checked out
        when(memberRepository.existsById(1L)).thenReturn(true);
        when(attendanceRepository.findByMemberMemberIdAndDate(1L, LocalDate.now()))
                .thenReturn(Optional.of(attendance));

        // Act & Assert
        assertThrows(InvalidInputException.class,
                () -> attendanceService.checkOut(1L));
    }
}